"use strict";
const assert = require("assert"); const fs = require("fs"); const os = require("os"); const path = require("path");
const am = require("../src/agentModel");
const f = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "am-")), "agent-model.json");
assert.strictEqual(am.setAgentModel(f, "Security", "OPUS"), "opus");
fs.writeFileSync(f, "\ufeff" + fs.readFileSync(f, "utf8").replace('"opus"', '"opus"')); // BOM tolerated
assert.strictEqual(am.setAgentModel(f, "COO", "fable"), "fable");
const c = JSON.parse(fs.readFileSync(f, "utf8"));
assert.deepStrictEqual(c.agents, { Security: "opus", COO: "fable" });
assert.throws(() => am.setAgentModel(f, "X", "gpt"));
assert.throws(() => am.setAgentModel(f, "a/b", "opus"));
assert.strictEqual(am.matchModelId("claude-sonnet-5-5"), "sonnet");
assert.strictEqual(am.matchModelId("zzz"), "");
const f2 = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "ae-")), "agent-model.json");
assert.strictEqual(am.setAgentEffort(f2, "Specs", "HIGH"), "high");
assert.strictEqual(am.effortFor(am.readCfg(f2), "Specs"), "high");
assert.strictEqual(am.effortFor(am.readCfg(f2), "Other"), "default");
assert.strictEqual(am.effortFor({ effortDefault: "low" }, "Other"), "low");
assert.strictEqual(am.effortFor({ effort: { A: "bogus" } }, "A"), "default");
assert.throws(() => am.setAgentEffort(f2, "X", "turbo"));
assert.throws(() => am.setAgentEffort(f2, "a/b", "high"));
assert.ok(JSON.parse(fs.readFileSync(f2, "utf8")).effort.Specs === "high");
console.log("agentModel: 15 checks passed");
